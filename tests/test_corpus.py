    ("order", "Требуется промпт-инженер для настройки GPT-ассистента в нашей поддержке. Оплата 3000 руб/час, 10 часов. tg: @support_boss"),
    ("order", "Сделайте нейросеть чтобы распознавать чеки на фото. Бюджет 50000. Срочно, до завтра."),
