@pytest.mark.parametrize(("kind", "text"), CASES, ids=[f"{i}-{k}" for i, (k, _) in enumerate(CASES)])
async def test_message_classification(pipe, db, chat_id, kind, text):
    oid = await pipe.process(make_raw(chat_id, text, author="u_" + str(abs(hash(text)) % 10**6)))
    if kind == "drop":
        assert oid is None
        return
    assert oid is not None
    row = db.one(store.ORDER_SELECT + " WHERE o.id=?", (oid,))
    if kind == "order":
        assert row["verdict"] in ("match", "maybe"), (row["verdict"], row["score"])
    elif kind == "scam":
        assert row["verdict"] == "scam"
    else:
        assert row["verdict"] in ("skip", "maybe", "match")
